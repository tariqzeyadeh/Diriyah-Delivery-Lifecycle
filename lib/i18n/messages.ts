const dictionaries: Record<Language, Record<MessageKey, string>> = { en: en as Record<MessageKey, string>, ar }

export function translate(
  lang: Language,
  key: MessageKey | string,
  vars?: Record<string, string | number>,
): string {
  const dict = dictionaries[lang] ?? dictionaries.en
  let text = dict[key as MessageKey] ?? dictionaries.en[key as MessageKey] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v))
    }
  }
  return text
}

